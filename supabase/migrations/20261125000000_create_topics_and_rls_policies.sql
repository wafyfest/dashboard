-- 6. Policy: College & Public can view topics only if hide is false AND outing_time <= now()
CREATE POLICY "topics_public_select"
  ON public.topics
  FOR SELECT
  TO authenticated, anon
  USING (
    hide = false
    AND outing_time <= now()
  );

-- 7. Policy: Admins have full access (INSERT, UPDATE, DELETE, SELECT)
CREATE POLICY "topics_admin_all"
  ON public.topics
  FOR ALL
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.profiles
      WHERE profiles.id = auth.uid()
      AND profiles.role IN ('admin', 'convenor')
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.profiles
      WHERE profiles.id = auth.uid()
      AND profiles.role IN ('admin', 'convenor')
    )
  );

